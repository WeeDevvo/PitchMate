// --- the 0-based pair, stated on its own -------------------------------------

/**
 * `SkillTier` and `RedeemOutcome` declare no explicit values in the backend, so
 * they are 0-based while the other four are 1-based. The suite above would catch
 * a shift through its literal-code assertion, but the consequence is worth
 * stating in its own right: this is the single most plausible defect in the
 * module, and it is silent — every tier still reads as *a* tier, just the wrong
 * one.
 */
// Feature: web-squads-screens, Property 37: The Enum_Code_Map round-trips every named value
// Validates: Requirements 16.6, 16.7, 20.3
describe('Enum_Code_Map — the two 0-based enums are not read as 1-based', () => {
  it('names Skill_Tier 0, 1, and 2 and refuses 3', () => {
    expect(skillTierFromCode(0)).toBe('beginner');
    expect(skillTierFromCode(1)).toBe('average');
    expect(skillTierFromCode(2)).toBe('strong');
    // A 1-based table would name this, and the correct table must not.
    expect(skillTierFromCode(3)).toBeUndefined();
  });

  it('names Redeem_Outcome 0, 1, and 2 and refuses 3', () => {
    expect(redeemOutcomeFromCode(0)).toBe('joined');
    expect(redeemOutcomeFromCode(1)).toBe('reactivated');
    expect(redeemOutcomeFromCode(2)).toBe('already-member');
    expect(redeemOutcomeFromCode(3)).toBeUndefined();
  });

  it('reads negative zero as the code zero, where a table carries one', () => {
    fc.assert(
      fc.property(fc.constant(-0), (negativeZero) => {
        // A property read converts `-0` to the same key as `0`, and the two are
        // the same number, so the 0-based tables name it and the 1-based ones do
        // not — asserted so the behaviour is a decision rather than an accident.
        expect(skillTierFromCode(negativeZero)).toBe('beginner');
        expect(redeemOutcomeFromCode(negativeZero)).toBe('joined');
        expect(memberRoleFromCode(negativeZero)).toBeUndefined();
        expect(membershipStateFromCode(negativeZero)).toBeUndefined();
        expect(squadFeatureFromCode(negativeZero)).toBeUndefined();
        expect(inviteStateFromCode(negativeZero)).toBeUndefined();
      }),
      { numRuns: 100 },
    );
  });

  it('keeps the 1-based four away from code 0', () => {
    fc.assert(
      fc.property(fc.constant(0), (zero) => {
        expect(memberRoleFromCode(zero)).toBeUndefined();
        expect(membershipStateFromCode(zero)).toBeUndefined();
        expect(squadFeatureFromCode(zero)).toBeUndefined();
        expect(inviteStateFromCode(zero)).toBeUndefined();
      }),
      { numRuns: 100 },
    );
  });
});

// --- every reader at once ----------------------------------------------------

/**
 * The six readers paired with the oracle for the table each is meant to be bound
 * to, so totality and correct binding can be stated once over all of them.
 */
const READERS: readonly {
  readonly label: string;
  readonly read: (code: unknown) => string | undefined;
  readonly oracle: ReadonlyMap<number, string>;
}[] = [
  {
    label: 'Member_Role',
    read: memberRoleFromCode,
    oracle: new Map<number, string>(MEMBER_ROLE_ORACLE),
  },
  {
    label: 'Membership_State',
    read: membershipStateFromCode,
    oracle: new Map<number, string>(MEMBERSHIP_STATE_ORACLE),
  },
  {
    label: 'Feature_Flag',
    read: squadFeatureFromCode,
    oracle: new Map<number, string>(SQUAD_FEATURE_ORACLE),
  },
  {
    label: 'Invite_State',
    read: inviteStateFromCode,
    oracle: new Map<number, string>(INVITE_STATE_ORACLE),
  },
  {
    label: 'Skill_Tier',
    read: skillTierFromCode,
    oracle: new Map<number, string>(SKILL_TIER_ORACLE),
  },
  {
    label: 'Redeem_Outcome',
    read: redeemOutcomeFromCode,
    oracle: new Map<number, string>(REDEEM_OUTCOME_ORACLE),
  },
];

// Feature: web-squads-screens, Property 37: The Enum_Code_Map round-trips every named value
// Validates: Requirements 16.6, 16.7, 20.3
describe('Enum_Code_Map — every reader is total over every input', () => {
  it('yields a string or nothing for any value of any type, and throws nothing', () => {
    fc.assert(
      fc.property(anyCandidateArb, (code) => {
        for (const { read } of READERS) {
          const named = read(code);

          expect(named === undefined || typeof named === 'string').toBe(true);
        }
      }),
      { numRuns: 1000 },
    );
  });

  it('never converts a value, so a hostile toString or valueOf never runs', () => {
    fc.assert(
      fc.property(integerCodeArb, (code) => {
        let conversions = 0;
        const hostile = {
          valueOf() {
            conversions += 1;
            return code;
          },
          toString() {
            conversions += 1;
            return String(code);
          },
        };

        for (const { read } of READERS) {
          expect(read(hostile)).toBeUndefined();
        }

        expect(conversions).toBe(0);
      }),
      { numRuns: 300 },
    );
  });

  it('survives a self-referencing structure and a throwing accessor', () => {
    const selfReferencing: Record<string, unknown> = { code: 1 };
    selfReferencing.self = selfReferencing;

    const cyclicArray: unknown[] = [1];
    cyclicArray.push(cyclicArray);

    const throwingGetter = {
      get code(): number {
        throw new Error('must never be read');
      },
    };

    for (const { read } of READERS) {
      for (const candidate of [selfReferencing, cyclicArray, throwingGetter]) {
        expect(read(candidate)).toBeUndefined();
      }
    }
  });

  it('is bound to its own table, for every integer at once', () => {
    fc.assert(
      fc.property(integerCodeArb, (code) => {
        // Read side by side, because a reader bound to the wrong table — a real
        // possibility with six near-identical one-line bindings — answers
        // plausibly on its own and only looks wrong next to the others. The four
        // 1-based tables overlap on 1 and 2, so the names, not just the presence
        // of a name, are what separate them.
        const answers = READERS.map(({ label, read }) => [label, read(code)]);
        const expected = READERS.map(({ label, oracle }) => [
          label,
          oracle.get(code),
        ]);

        expect(answers).toEqual(expected);
      }),
      { numRuns: 1000 },
    );
  });
});
