/**
 * Property tests for the Enum_Code_Map, placed beside the module they cover as
 * the design's Testing Strategy asks and running well above the 100-iteration
 * floor (20.1).
 *
 * These carry **Property 37: The Enum_Code_Map round-trips every named value** —
 * for any named value of Member_Role, Membership_State, Feature_Flag, Skill_Tier,
 * Invite_State (and Redeem_Outcome, which the same map serves), mapping the value
 * to its code and back yields the same named value (16.7); and for any integer
 * outside a table's code set, that table's reader yields no named value (16.6).
 *
 * Two things about how this is written matter more than the run counts.
 *
 * First, the **codes are asserted literally against an oracle read from the
 * backend enums**, not derived from the module under test. A generated round trip
 * cannot catch a wrong code: `codeFrom…` is built by reversing the very table
 * `…FromCode` reads, so a table that named `1 → beginner` would round-trip
 * perfectly and still misread every wire body. The oracle below was transcribed
 * from `Domain/Squads/SquadRole.cs`, `MembershipState.cs`, `SquadFeature.cs`,
 * `InviteState.cs`, `Domain/Rating/SkillTier.cs`, and
 * `Application/Squads/UseCases/RedeemInviteResult.cs`, and it is the only place
 * here that repeats a numeric literal.
 *
 * Second, the out-of-range side is stated as an **equivalence over arbitrary
 * integers** — a reader is asked to agree with the oracle for every integer, not
 * merely to reject a hand-picked few. `SkillTier` code `3` and `RedeemOutcome`
 * code `3` are additionally generated by name, because those two backend enums
 * declare no explicit values and so start at `0`: a 1-based reading would name
 * `3` and shift every tier by one, and that is exactly the defect this file
 * exists to catch.
 */

